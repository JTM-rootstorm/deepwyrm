pub(super) fn title(section: &str) -> String {
    let mut result = String::new();
    for (index, word) in section.split('_').enumerate() {
        if index != 0 {
            result.push(' ');
        }
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            result.push(first.to_ascii_uppercase());
            result.extend(chars);
        }
    }
    result
}

