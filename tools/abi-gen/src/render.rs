pub(super) fn rust_value(ty: &str, value: i128, newtypes: &[Newtype]) -> String {
    if newtypes.iter().any(|item| item.name == ty) {
        format!("{ty}({value})")
    } else {
        value.to_string()
    }
}

pub(super) fn render_c(model: &Model) -> Result<String> {
    let mut out = generated_preamble("/*");
    // Close the deliberately simple block-comment preamble lines.
    out = out.replace("\n\n", " */\n\n").replace("\n/* Do", "\n * Do");
    writeln!(out, "#ifndef DEEPWYRM_ABI_GENERATED_H").unwrap();
    writeln!(out, "#define DEEPWYRM_ABI_GENERATED_H\n").unwrap();
    writeln!(out, "#include <stddef.h>").unwrap();
    writeln!(out, "#include <stdint.h>\n").unwrap();
    writeln!(out, "#if defined(__cplusplus)").unwrap();
    writeln!(out, "#define DW_STATIC_ASSERT static_assert").unwrap();
    writeln!(out, "#define DW_ALIGNOF alignof").unwrap();
    writeln!(out, "#else").unwrap();
    writeln!(out, "#define DW_STATIC_ASSERT _Static_assert").unwrap();
    writeln!(out, "#define DW_ALIGNOF _Alignof").unwrap();
    writeln!(out, "#endif\n").unwrap();
    writeln!(
        out,
        "#define DW_ABI_VERSION UINT32_C({})\n",
        model.abi.version
    )
    .unwrap();
    let layouts = type_layouts(&model.newtypes);
    for item in &model.newtypes {
        writeln!(out, "/* {} */", item.doc).unwrap();
        writeln!(out, "typedef {} {};\n", c_primitive(&item.base)?, item.name).unwrap();
        let (size, align) = layouts[&item.name];
        writeln!(
            out,
            "DW_STATIC_ASSERT(sizeof({}) == {}, \"{} size\");",
            item.name, size, item.name
        )
        .unwrap();
        writeln!(
            out,
            "DW_STATIC_ASSERT(DW_ALIGNOF({}) == {}, \"{} alignment\");\n",
            item.name, align, item.name
        )
        .unwrap();
    }
    for set in &model.value_sets {
        for item in &set.values {
            writeln!(out, "/* {} */", item.doc).unwrap();
            writeln!(
                out,
                "#define {}_{} (({})({}))",
                set.prefix, item.name, set.rust_type, item.value
            )
            .unwrap();
        }
        out.push('\n');
    }
    writeln!(out, "/* Mask of every DwRights bit known to ABI 0. */").unwrap();
    writeln!(
        out,
        "#define DW_RIGHTS_KNOWN_MASK ((DwRights)({}))",
        model.known_rights_mask
    )
    .unwrap();
    for entry in &model.object_rights {
        writeln!(
            out,
            "/* Compatible rights for the {} object type. */",
            entry.object
        )
        .unwrap();
        writeln!(
            out,
            "#define DW_OBJECT_COMPATIBLE_RIGHTS_{} ((DwRights)({}))",
            entry.object, entry.mask
        )
        .unwrap();
    }
    out.push('\n');
    writeln!(
        out,
        "static inline DwRights dw_object_compatible_rights(DwObjectType object_type) {{"
    )
    .unwrap();
    writeln!(out, "    switch (object_type) {{").unwrap();
    for entry in &model.object_rights {
        writeln!(
            out,
            "    case DW_OBJECT_TYPE_{}: return DW_OBJECT_COMPATIBLE_RIGHTS_{};",
            entry.object, entry.object
        )
        .unwrap();
    }
    writeln!(out, "    default: return (DwRights)0;").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}\n").unwrap();
    writeln!(
        out,
        "static inline int dw_rights_are_known(DwRights rights) {{"
    )
    .unwrap();
    writeln!(out, "    return (rights & ~DW_RIGHTS_KNOWN_MASK) == 0;").unwrap();
    writeln!(out, "}}\n").unwrap();
    writeln!(
        out,
        "static inline int dw_rights_are_compatible(DwObjectType object_type, DwRights rights) {{"
    )
    .unwrap();
    writeln!(
        out,
        "    DwRights compatible = dw_object_compatible_rights(object_type);"
    )
    .unwrap();
    writeln!(out, "    return (rights & ~compatible) == 0;").unwrap();
    writeln!(out, "}}\n").unwrap();
    writeln!(out, "/* Mask of every DwSignals bit known to ABI 0. */").unwrap();
    writeln!(
        out,
        "#define DW_SIGNALS_KNOWN_MASK ((DwSignals)({}))",
        model.known_signals_mask
    )
    .unwrap();
    for entry in &model.object_signals {
        writeln!(
            out,
            "/* Applicable wait signals for the {} object type. */",
            entry.object
        )
        .unwrap();
        writeln!(
            out,
            "#define DW_OBJECT_COMPATIBLE_SIGNALS_{} ((DwSignals)({}))",
            entry.object, entry.mask
        )
        .unwrap();
    }
    out.push('\n');
    writeln!(
        out,
        "static inline DwSignals dw_object_compatible_signals(DwObjectType object_type) {{"
    )
    .unwrap();
    writeln!(out, "    switch (object_type) {{").unwrap();
    for entry in &model.object_signals {
        writeln!(
            out,
            "    case DW_OBJECT_TYPE_{}: return DW_OBJECT_COMPATIBLE_SIGNALS_{};",
            entry.object, entry.object
        )
        .unwrap();
    }
    writeln!(out, "    default: return (DwSignals)0;").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}\n").unwrap();
    writeln!(
        out,
        "static inline int dw_signals_are_known(DwSignals signals) {{"
    )
    .unwrap();
    writeln!(out, "    return (signals & ~DW_SIGNALS_KNOWN_MASK) == 0;").unwrap();
    writeln!(out, "}}\n").unwrap();
    writeln!(out, "static inline int dw_signals_are_compatible(DwObjectType object_type, DwSignals signals) {{").unwrap();
    writeln!(
        out,
        "    DwSignals compatible = dw_object_compatible_signals(object_type);"
    )
    .unwrap();
    writeln!(out, "    return (signals & ~compatible) == 0;").unwrap();
    writeln!(out, "}}\n").unwrap();
    for constant in &model.constants {
        writeln!(out, "/* {} */", constant.doc).unwrap();
        writeln!(
            out,
            "#define {} (({})({}))",
            constant.name,
            c_named(&constant.ty)?,
            constant.value
        )
        .unwrap();
    }
    out.push('\n');
    for syscall in &model.syscalls {
        writeln!(out, "/* {} */", syscall.doc).unwrap();
        writeln!(
            out,
            "#define DW_SYSCALL_{} ((DwSyscallId)(UINT32_C(0x{:08x})))",
            syscall.name.to_ascii_uppercase(),
            syscall.number
        )
        .unwrap();
    }
    out.push('\n');

    for record in &model.records {
        writeln!(out, "/* {} */", record.doc).unwrap();
        writeln!(out, "typedef struct {} {{", record.name).unwrap();
        for field in &record.fields {
            writeln!(out, "    /* {} */", field.doc).unwrap();
            match &field.ty {
                FieldType::Named(name) => {
                    writeln!(out, "    {} {};", c_named(name)?, field.name).unwrap();
                }
                FieldType::Array(name, count) => {
                    writeln!(out, "    {} {}[{}];", c_named(name)?, field.name, count).unwrap();
                }
            }
        }
        writeln!(out, "}} {};", record.name).unwrap();
        writeln!(
            out,
            "#define {} ((uint32_t)({}))",
            record_size_constant(&record.name),
            record.size
        )
        .unwrap();
        writeln!(
            out,
            "DW_STATIC_ASSERT(sizeof({}) == {}, \"{} size\");",
            record.name, record.size, record.name
        )
        .unwrap();
        writeln!(
            out,
            "DW_STATIC_ASSERT(DW_ALIGNOF({}) == {}, \"{} alignment\");",
            record.name, record.align, record.name
        )
        .unwrap();
        for (field, offset) in record.fields.iter().zip(&record.offsets) {
            writeln!(
                out,
                "DW_STATIC_ASSERT(offsetof({}, {}) == {}, \"{}.{} offset\");",
                record.name, field.name, offset, record.name, field.name
            )
            .unwrap();
        }
        out.push('\n');
    }
    writeln!(out, "#undef DW_ALIGNOF").unwrap();
    writeln!(out, "#undef DW_STATIC_ASSERT\n").unwrap();
    writeln!(out, "#endif /* DEEPWYRM_ABI_GENERATED_H */").unwrap();
    Ok(out)
}

pub(super) fn c_primitive(name: &str) -> Result<&'static str> {
    match name {
        "u8" => Ok("uint8_t"),
        "u16" => Ok("uint16_t"),
        "u32" => Ok("uint32_t"),
        "u64" => Ok("uint64_t"),
        "i8" => Ok("int8_t"),
        "i16" => Ok("int16_t"),
        "i32" => Ok("int32_t"),
        "i64" => Ok("int64_t"),
        other => Err(Error::new(format!("unsupported C primitive `{other}`"))),
    }
}

pub(super) fn c_named(name: &str) -> Result<&str> {
    match name {
        "u8" | "u16" | "u32" | "u64" | "i8" | "i16" | "i32" | "i64" => c_primitive(name),
        _ => Ok(name),
    }
}

fn rust_syscall_variant(name: &str) -> String {
    name.split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn rust_phase_variant(phase: &str) -> Result<&'static str> {
    match phase {
        "DW0-A" => Ok("Dw0A"),
        "DW0-B" => Ok("Dw0B"),
        "DW0-C" => Ok("Dw0C"),
        "DW0-D" => Ok("Dw0D"),
        "DW0-E" => Ok("Dw0E"),
        "DW0-F" => Ok("Dw0F"),
        "DW0-G" => Ok("Dw0G"),
        "DW0-H" => Ok("Dw0H"),
        other => Err(Error::new(format!(
            "unsupported syscall implementation phase `{other}`"
        ))),
    }
}

